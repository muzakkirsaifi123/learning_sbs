#!/usr/bin/env python3
"""
Sync Notion pages into MkDocs docs/notion/ folder as Markdown files.
Automatically updates the Notion section in mkdocs.yml.

Usage:
  NOTION_TOKEN=ntn_xxx NOTION_PAGE_ID=1fd9f2a93248826a83de816c57fc66b8 python3 notion_sync.py

Idempotent by design: re-running against an unchanged Notion tree produces
byte-identical output. Page identity is tracked by Notion page ID (not by
title/slug) in .notion-sync/manifest.json, which is what makes rename and
delete detection possible across runs — see README.md for the full pipeline
description.
"""

